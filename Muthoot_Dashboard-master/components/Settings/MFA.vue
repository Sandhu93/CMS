<template>
  <div
    class="absolute top-0 left-0 w-screen min-h-screen flex justify-center items-center bg-new-black/60 z-30"
  >
    <div
      class="w-[450px] p-5 text-white font-quicksand flex flex-col gap-3 bg-new-blue bg-opacity-[0.15] backdrop-blur-lg rounded-lg relative"
    >
      <div class="flex justify-between w-full">
        <span class="text-white text-2xl"
          >Setup 2-Factor Auth</span
        >
        <SVGCloseCross
          @click="emit('close')"
          class="text-white text-2xl cursor-pointer"
        />
      </div>
      <section class="w-full flex gap-2 cursor-default">
        <div class="w-full flex flex-col gap-1">
          <h3 class="font-bold"> {{ `1) Install 2FA` }} </h3>
          <span class="text-sm">Download and Install an authenticator app (e.g. Google Authenticator, Authy, etc.)</span>
        </div>
      </section>
      <section
      class="w-full flex flex-col gap-1 cursor-default"
      >
      <h3 class="font-bold"> {{ `2) Scan the QR` }} </h3>
        <span class="text-sm font-light">Scan QR-code or enter the secret in your app.</span>
        <img
        v-if="!loading"
        :src="data.qrCodeUrl"
        style="outline: none"
        class="w-64 h-64 rounded-md mx-auto my-4"
        />
        <div v-else class="w-64 h-64 rounded-md mx-auto mt-4 animate-pulse bg-white/10"></div>
        <div v-if="!loading" class="w-full h-10 relative rounded-md border border-white/30">
          <input
          style="outline: none"
          :value="data.secret"
          readonly
          class="bg-transparent w-11/12 h-full p-3 text-xs"
          ref="accessElement"
          />
          <SVGCopyClipboard class="cursor-pointer absolute z-30 top-1 right-1" @click="copy"/>
        </div>
        <div v-else class="w-full h-10 rounded-md mx-auto my-4 animate-pulse bg-white/10"></div>
      </section>
      <section
      class="w-full flex flex-col gap-1 cursor-default"
      >
      <h3 class="font-bold"> {{ `3) Enter the generated code` }} </h3>
        <span class="text-sm font-light">Enter the code that has been generated by the authenticator in the field below:</span>
        <div v-if="!loading" class="w-full h-10 relative rounded-md border border-white/30 mt-1">
          <input
            v-model="token"
            placeholder="6-digit code"
            @input="verifyToken"
            :disabled="tokenLoading"
            class="bg-transparent rounded-md w-full h-10 p-3 text-sm outline-none"
          />
          <SVGLoading class="cursor-pointer absolute z-30 top-2 right-2" v-if="tokenLoading" />
        </div>
        <div v-else class="w-full h-10 rounded-md mx-auto my-4 animate-pulse bg-white/10"></div>
      </section>
    </div>
  </div>
</template>

<script setup>
  import { useNotificationsStore } from "@/store/notifications";
  const data = ref({});
  const emit = defineEmits(["close"]);
  const config = useRuntimeConfig();
  const loading = ref(true);
  const notifications = useNotificationsStore();
  const accessElement = ref(null);
  const token = ref(null);
  const tokenLoading = ref(false);
  const { add } = notifications;

  async function verifyToken() {
    if(token.value === null) return;
    if(token.value.length !== 6) {
      return;
    }
    if(isNaN(token.value)) {
      return;
    }
    tokenLoading.value = true;
    const { data: verify, error } = await useFetch(`${config.public.api}/api/mfaGenerate`, {
      method: "POST",
      headers: {
        authorization: localStorage.getItem("token"),
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        token: parseInt(token.value),
        secret: data.value.secret,
      }),
    });
    if(error.value) {
        tokenLoading.value = false;
        token.value = "";
        add({ 
          title: `Error ${error.value.statusCode}`,
          text: `${error.value.statusMessage}`,
        });
        return;
    }
    if(verify.value.statusCode === 200) {
      tokenLoading.value = false;
      token.value = "";
      add({ 
        title: '2FA Enabled',
        text: `2FA has been enabled`,
      });
      emit("close");
    } else {
      tokenLoading.value = false;
      token.value = "";
      add({ 
        title: 'Invalid Token',
        text: `The token you entered is invalid`,
      });
    }
  }

  function copy(){
      if(document === undefined) return;
        accessElement.value.focus();
        accessElement.value.select();
        accessElement.value.setSelectionRange(0, 99999);
        document.execCommand('copy');
        add({ 
        title: 'Code Copied',
        text: `Access code has been copied to the clipboard`,
      });
  }

  async function loadData() {
    const { data: totp, error } = await useFetch(`${config.public.api}/api/mfaGenerate`, {
        method: "GET",
        headers: {
            authorization: `${localStorage.getItem("token")}`,
        },
    });
    if(error.value) {
      return;
    }
  
    if(totp.value.statusCode === 200) {
        data.value = totp.value.data;
        loading.value = false;
    }
  }
  loadData();
// defineExpose({ editUserDetails });
</script>
